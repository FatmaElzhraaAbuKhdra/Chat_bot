"""
erp_actions/models.py — Data models for the ERP Action Engine.
Defines action types, statuses, and the ActionPlan lifecycle.
"""
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional
import time
import uuid


class ActionStatus(str, Enum):
    """Lifecycle status of an ERP action."""
    PLANNED    = "planned"       # Action proposed, awaiting user confirmation
    CONFIRMED  = "confirmed"     # User said yes, awaiting execution
    EXECUTING  = "executing"     # DML in progress
    COMPLETED  = "completed"     # Successfully executed
    FAILED     = "failed"        # Execution failed
    REJECTED   = "rejected"      # User declined the action
    CANCELLED  = "cancelled"     # System or timeout cancellation
    ROLLED_BACK = "rolled_back"  # Compensating action executed


class ActionType(str, Enum):
    """All supported ERP action types."""
    # Customer / Supplier
    CREATE_CUSTOMER    = "create_customer"
    CREATE_SUPPLIER    = "create_supplier"
    UPDATE_CUSTOMER    = "update_customer"
    UPDATE_SUPPLIER    = "update_supplier"
    DEACTIVATE_CUSTOMER = "deactivate_customer"
    DEACTIVATE_SUPPLIER = "deactivate_supplier"

    # Items
    CREATE_ITEM        = "create_item"
    UPDATE_ITEM        = "update_item"
    UPDATE_ITEM_PRICE  = "update_item_price"

    # Payments
    CREATE_PAYMENT     = "create_payment"
    CREATE_COLLECTION  = "create_collection"

    # Workflow / Approvals
    APPROVE_REQUEST    = "approve_request"
    REJECT_REQUEST     = "reject_request"
    SEND_FOR_APPROVAL  = "send_for_approval"
    CLOSE_WORKFLOW     = "close_workflow"
    REOPEN_WORKFLOW    = "reopen_workflow"

    # Accounting
    CREATE_VOUCHER     = "create_voucher"

    # Generic
    CUSTOM_ACTION      = "custom_action"


