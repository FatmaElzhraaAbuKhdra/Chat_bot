# ── Severity / Risk Level ─────────────────────────────────────────
class ActionRisk(str, Enum):
    LOW    = "low"       # Read-like: status changes, soft updates
    MEDIUM = "medium"    # Creates new records
    HIGH   = "high"      # Financial: payments, vouchers
    CRITICAL = "critical"  # Bulk changes, deletions, approvals with financial impact


@dataclass
class ActionPlan:
    """
    A planned ERP action awaiting confirmation and execution.
    This is the central artifact of the Action Engine.
    """
    id: str = ""
    action_type: str = ""
    status: str = ActionStatus.PLANNED.value
    risk_level: str = ActionRisk.MEDIUM.value

    # Context
    user_id: str = ""
    company_code: str = ""
    fiscal_year: str = ""

    # What to do
    description_ar: str = ""    # Arabic description shown to user
    description_en: str = ""    # English description for logs
    target_table: str = ""      # Primary ERP table affected
    target_record_id: str = ""  # Record identifier (CUSTID, ITEMID, etc.)
    parameters: dict = field(default_factory=dict)  # Action parameters

    # SQL to execute (generated by planner, validated before exec)
    sql_statements: list[str] = field(default_factory=list)
    sql_params: list[tuple] = field(default_factory=list)

    # Validation
    validation_errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    requires_approval: bool = False  # Needs higher-level approval before exec

    # Execution results
    result_message: str = ""
    affected_rows: int = 0
    error_message: str = ""

    # Timestamps
    created_at: float = 0.0
    confirmed_at: float = 0.0
    executed_at: float = 0.0
    completed_at: float = 0.0

    def __post_init__(self):
        if not self.id:
            self.id = uuid.uuid4().hex[:16]
        if not self.created_at:
            self.created_at = time.time()

    def to_dict(self) -> dict:
        label_ar, label_en = ACTION_LABELS.get(
            self.action_type, ("إجراء", "Action")
        )
        return {
            "id": self.id,
            "action_type": self.action_type,
            "action_label_ar": label_ar,
            "action_label_en": label_en,
            "status": self.status,
            "risk_level": self.risk_level,
            "description_ar": self.description_ar,
            "description_en": self.description_en,
            "target_table": self.target_table,
            "target_record_id": self.target_record_id,
            "parameters": self.parameters,
            "validation_errors": self.validation_errors,
            "warnings": self.warnings,
            "requires_approval": self.requires_approval,
            "result_message": self.result_message,
            "affected_rows": self.affected_rows,
            "error_message": self.error_message,
            "created_at": self.created_at,
            "confirmed_at": self.confirmed_at,
            "executed_at": self.executed_at,
        }

    def confirmation_card(self) -> dict:
        """Generate an action confirmation card for the frontend."""
        label_ar, _ = ACTION_LABELS.get(
            self.action_type, ("إجراء", "Action")
        )
        params_display = []
        for k, v in self.parameters.items():
            params_display.append({"key": k, "value": str(v)})

        return {
            "type": "action_confirmation",
            "action_id": self.id,
            "action_type": self.action_type,
            "action_label": label_ar,
            "risk_level": self.risk_level,
            "description": self.description_ar,
            "parameters": params_display,
            "warnings": self.warnings,
            "requires_approval": self.requires_approval,
        }

    def result_card(self) -> dict:
        """Generate an action result card for the frontend."""
        label_ar, _ = ACTION_LABELS.get(
            self.action_type, ("إجراء", "Action")
        )
        return {
            "type": "action_result",
            "action_id": self.id,
            "action_label": label_ar,
            "status": self.status,
            "success": self.status == ActionStatus.COMPLETED.value,
            "message": self.result_message or self.error_message,
            "affected_rows": self.affected_rows,
        }


@dataclass
class AuditEntry:
    """Immutable audit log entry for every action state change."""
    id: str = ""
    action_id: str = ""
    user_id: str = ""
    action_type: str = ""
    status_from: str = ""
    status_to: str = ""
    detail: str = ""
    sql_executed: str = ""
    timestamp: float = 0.0

    def __post_init__(self):
        if not self.id:
            self.id = uuid.uuid4().hex[:12]
        if not self.timestamp:
            self.timestamp = time.time()
